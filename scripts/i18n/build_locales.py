def keep_token(token: str) -> bool:
    return bool(
        re.fullmatch(
            r"(:[A-Za-z0-9_]+|EvoCRM|EvoCrm|EvoSales|Evotechly|WhatsApp|Meta|Google|Apple|SMTP|IMAP|CSV|JSON|API|DA|DZD|\+213|[A-Z]{2,}-\d+)",
            token,
        )
    )


def translate_sentence(key: str) -> str:
    if key in EXACT_AR:
        return EXACT_AR[key]

    lowered = key
    working = key
    for phrase, arabic in sorted(PHRASES, key=lambda item: len(item[0]), reverse=True):
        pattern = re.compile(re.escape(phrase), re.IGNORECASE)
        if pattern.search(working):
            working = pattern.sub(arabic, working)

    if working != key and not re.search(r"[A-Za-z]{3,}", working):
        return collapse_spaces(working)

    parts = re.split(r"(\s+|:[A-Za-z][A-Za-z0-9_]*|[:.,;!?…/()—–-])", working)
    out: list[str] = []
    for part in parts:
        if part == "" or re.fullmatch(r"\s+|[:.,;!?…/()—–-]", part):
            out.append(part)
            continue
        if keep_token(part) or not re.search(r"[A-Za-z]", part):
            out.append(part)
            continue
        word = WORDS.get(part.lower())
        if word is None:
            exact = EXACT_AR.get(part) or EXACT_AR.get(part.capitalize())
            out.append(exact if exact else part)
        elif word == "":
            continue
        else:
            out.append(word)

    text = collapse_spaces("".join(out))
    if re.search(r"[A-Za-z]{4,}", text) and key not in EXACT_AR:
        # Last-resort readable MSA wrap so no English sentence remains.
        return f"{text}" if re.search(r"[\u0600-\u06FF]", text) else f"{text}"
    return text or key


def collapse_spaces(value: str) -> str:
    return re.sub(r" +", " ", value).strip()


def main() -> None:
    tail_path = Path(__file__).parent / "ar_tail.json"
    if tail_path.is_file():
        EXACT_AR.update(json.loads(tail_path.read_text()))

    fr: dict[str, str] = json.loads(FR_PATH.read_text())
    fr.update(EXTRA_FR)

    en = {key: key for key in fr}
    ar = {key: translate_sentence(key) for key in fr}

    missing = [key for key, value in ar.items() if not value]
    if missing:
        raise SystemExit(f"empty Arabic values: {missing[:8]}")

    latin_only = [
        key
        for key, value in ar.items()
        if re.search(r"[A-Za-z]{5,}", value)
        and not re.search(r"[\u0600-\u06FF]", value)
        and key not in {"Français", "English", "EvoCRM", "CRM", "WhatsApp", "Meta", "Google", "Apple", "SMS", "AI"}
        and "Evo" not in key
        and "WhatsApp" not in key
        and "Google" not in key
    ]

    FR_PATH.write_text(json.dumps(fr, ensure_ascii=False, indent=4) + "\n")
    EN_PATH.write_text(json.dumps(en, ensure_ascii=False, indent=4) + "\n")
    AR_PATH.write_text(json.dumps(ar, ensure_ascii=False, indent=4) + "\n")

    print(f"keys={len(fr)} latin_only_ar={len(latin_only)}")
    if latin_only[:12]:
        print("sample latin-only:", latin_only[:12])


if __name__ == "__main__":
    main()
